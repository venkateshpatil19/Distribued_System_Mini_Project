export function Modal({ open, onClose, title, children, footer }: { open: boolean; onClose: () => void; title: string; children: ReactNode; footer?: ReactNode }) {
  const ref = useRef<HTMLDivElement>(null);
  const titleId = useId();
  useEffect(() => {
    if (!open) return;
    const prev = document.activeElement as HTMLElement | null;
    const el = ref.current;
    const focusables = () => Array.from(el?.querySelectorAll<HTMLElement>('button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])') ?? []).filter((x) => !x.hasAttribute("disabled"));
    focusables()[0]?.focus();
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
      if (e.key === "Tab") {
        // Keep focus inside the dialog.
        const f = focusables();
        if (!f.length) return;
        if (e.shiftKey && document.activeElement === f[0]) {
          e.preventDefault();
          f[f.length - 1].focus();
        } else if (!e.shiftKey && document.activeElement === f[f.length - 1]) {
          e.preventDefault();
          f[0].focus();
        }
      }
    };
    document.addEventListener("keydown", onKey);
    document.body.style.overflow = "hidden";
    return () => {
      document.removeEventListener("keydown", onKey);
      document.body.style.overflow = "";
      prev?.focus();
    };
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className="fixed inset-0 z-[80] flex items-end justify-center p-4 sm:items-center" role="presentation">
      <div className="absolute inset-0 bg-black/40 backdrop-blur-sm" onClick={onClose} aria-hidden />
      <div ref={ref} role="dialog" aria-modal="true" aria-labelledby={titleId} className="card relative z-10 max-h-[90vh] w-full max-w-lg overflow-y-auto p-5">
        <div className="mb-3 flex items-start justify-between gap-4">
          <h2 id={titleId} className="text-base font-semibold">{title}</h2>
          <button className="rounded-lg p-1 text-muted hover:bg-surface-2 hover:text-ink" onClick={onClose} aria-label="Close dialog">
            <X className="h-4 w-4" />
          </button>
        </div>
        <div className="text-sm">{children}</div>
        {footer && <div className="mt-5 flex flex-wrap justify-end gap-2">{footer}</div>}
      </div>
    </div>
  );
}

// Confirmation for destructive or disruptive actions; runs the action and reports the real outcome.
export function ConfirmButton({
  label, title, body, confirmLabel, onConfirm, danger = true, icon, className, disabled,
}: {
  label: ReactNode; title: string; body: ReactNode; confirmLabel: string; onConfirm: () => Promise<unknown>;
  danger?: boolean; icon?: ReactNode; className?: string; disabled?: boolean;
}) {
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const run = async () => {
    setBusy(true);
    setErr(null);
    try {
      await onConfirm();
      setOpen(false);
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  };
  return (
    <>
      <button type="button" className={cx(danger ? "btn-danger" : "btn-ghost", className)} onClick={() => { setErr(null); setOpen(true); }} disabled={disabled}>
        {icon}
        {label}
      </button>
      <Modal open={open} onClose={() => !busy && setOpen(false)} title={title}
        footer={
          <>
            <button className="btn-ghost" onClick={() => setOpen(false)} disabled={busy}>Cancel</button>
            <button className={danger ? "btn-danger" : "btn-primary"} onClick={run} disabled={busy}>
              {busy && <Loader2 className="h-4 w-4 animate-spin" aria-hidden />}
              {confirmLabel}
            </button>
          </>
        }>
        <div className="space-y-3 text-muted">{body}</div>
        {err && <div className="mt-3"><ErrorState message={err} /></div>}
      </Modal>
    </>
  );
}

