export function LastUpdated({ at, label = "Updated" }: { at: number | string | null; label?: string }) {
  const [, force] = useState(0);
  useEffect(() => {
    const t = setInterval(() => force((x) => x + 1), 5000);
    return () => clearInterval(t);
  }, []);
  if (!at) return null;
  const iso = typeof at === "number" ? new Date(at).toISOString() : at;
  return (
    <time dateTime={iso} className="text-xs text-muted" title={new Date(iso).toLocaleString()}>
      {label} {relativeTime(iso)}
    </time>
  );
}

// ---------- toasts ----------

type Toast = { id: number; kind: "success" | "error"; text: string };
const ToastCtx = createContext<(kind: Toast["kind"], text: string) => void>(() => {});

export function ToastProvider({ children }: { children: ReactNode }) {
  const [toasts, setToasts] = useState<Toast[]>([]);
  const push = useCallback((kind: Toast["kind"], text: string) => {
    const id = Date.now() + Math.random();
    setToasts((t) => [...t.slice(-3), { id, kind, text }]);
    setTimeout(() => setToasts((t) => t.filter((x) => x.id !== id)), kind === "error" ? 7000 : 3500);
  }, []);
  return (
    <ToastCtx.Provider value={push}>
      {children}
      <div aria-live="polite" className="pointer-events-none fixed inset-x-0 bottom-20 z-[70] flex flex-col items-center gap-2 px-4 sm:bottom-6">
        {toasts.map((t) => (
          <div
            key={t.id}
            role={t.kind === "error" ? "alert" : "status"}
            className={cx("pointer-events-auto flex max-w-md items-start gap-2 rounded-xl border px-4 py-2.5 text-sm shadow-lift glass",
              t.kind === "error" ? "border-bad/40 text-bad" : "border-ok/40 text-ink")}
          >
            {t.kind === "error" ? <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden /> : <Check className="mt-0.5 h-4 w-4 shrink-0 text-ok" aria-hidden />}
            <span>{t.text}</span>
          </div>
        ))}
      </div>
    </ToastCtx.Provider>
  );
}

export const useToast = () => useContext(ToastCtx);

// ---------- copy ----------

export function CopyButton({ text, label = "Copy", className }: { text: string; label?: string; className?: string }) {
  const [state, setState] = useState<"idle" | "ok" | "err">("idle");
  const copy = async () => {
    try {
      if (!navigator.clipboard) throw new Error("Clipboard API unavailable");
      await navigator.clipboard.writeText(text);
      setState("ok");
    } catch {
      setState("err");
    }
    setTimeout(() => setState("idle"), 2000);
  };
  return (
    <button type="button" onClick={copy} className={cx("btn-ghost !px-2.5 !py-1 text-xs", className)} aria-live="polite">
      {state === "ok" ? <Check className="h-3.5 w-3.5 text-ok" aria-hidden /> : state === "err" ? <X className="h-3.5 w-3.5 text-bad" aria-hidden /> : <Copy className="h-3.5 w-3.5" aria-hidden />}
      {state === "ok" ? "Copied" : state === "err" ? "Copy failed" : label}
    </button>
  );
}

