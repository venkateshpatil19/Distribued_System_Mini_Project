export function cx(...c: Array<string | false | null | undefined>) {
  return c.filter(Boolean).join(" ");
}

export function Card({ children, className, accent }: { children: ReactNode; className?: string; accent?: "ok" | "warn" | "bad" | "info" | "accent" }) {
  const border = accent ? { ok: "border-l-ok", warn: "border-l-warn", bad: "border-l-bad", info: "border-l-info", accent: "border-l-accent" }[accent] : "";
  return <div className={cx("card min-w-0 p-5", accent && "card-accent", border, className)}>{children}</div>;
}

